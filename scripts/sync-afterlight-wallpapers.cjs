'use strict';
/* Mechanical, local-only import of Sadeq Rezai's Afterlight 1.7 artwork.
 * Original sources remain untouched. No dependency download or network I/O.
 * The resulting external scripts work under Seneschal's existing strict CSP.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const appRoot = path.resolve(__dirname, '..');
const requestedSource = process.argv[2] || process.env.SENESCHAL_AFTERLIGHT_SOURCE;
if (!requestedSource) throw new Error('Supply the Afterlight web folder: node scripts/sync-afterlight-wallpapers.cjs <source-folder>, or set SENESCHAL_AFTERLIGHT_SOURCE.');
const sourceRoot = path.resolve(requestedSource);
const destination = path.join(appRoot, 'app', 'wallpapers');
const sha = text => crypto.createHash('sha256').update(text).digest('hex');
function replaceOnce(source, before, after, label) {
  if (source.split(before).length !== 2) throw new Error(`Afterlight source changed: ${label}`);
  return source.replace(before, after);
}

const worldsRaw = fs.readFileSync(path.join(sourceRoot, 'worlds.js'));
const sceneRaw = fs.readFileSync(path.join(sourceRoot, 'scene.js'));
const worlds = worldsRaw.toString('utf8').replace(/\r\n/g, '\n');
const scene = sceneRaw.toString('utf8').replace(/\r\n/g, '\n');
const stamp = `/* Imported from Sadeq Rezai's Afterlight 1.7. Original art/renderer attribution retained.\n * Generated by scripts/sync-afterlight-wallpapers.cjs; edit that adapter, not this generated file.\n * Original source-file SHA-256: worlds ${sha(worldsRaw)}; scene ${sha(sceneRaw)}. */\n`;
const worldOutput = stamp + replaceOnce(worlds, 'window.AfterlightWorlds={catalog,create,spots};', 'window.SeneschalAfterlightWorlds={catalog,create,spots};', 'world catalog export');
let body = replaceOnce(scene, 'active=true,hostPaused=false', 'active=false,hostPaused=false', 'start paused');
body = body.replaceAll("'afterlight.v1'", "'seneschal.afterlight.memory.city'").replaceAll("'afterlight.worlds.v1'", "'seneschal.afterlight.memory.worlds'");
body = replaceOnce(body,
  "  canvas.addEventListener('pointermove',e=>{const p=worldPoint(e);pointer(p.x,p.y);});\n  canvas.addEventListener('pointerleave',()=>{mouse.nx=0;mouse.ny=0;hovered(null);document.body.classList.remove('pointer-hot');});\n  canvas.addEventListener('pointerdown',e=>{if(e.button!==0)return;const p=worldPoint(e);pointer(p.x,p.y,true);});",
  '  // Seneschal explicitly forwards pointer input; the background never captures app input.', 'input listener isolation');
body = replaceOnce(body, '    prefs:()=>({...prefs}),defaults:()=>sceneDefaults(prefs.scene),set,effect,',
  '    prefs:()=>({...prefs}),defaults:()=>sceneDefaults(prefs.scene),set,effect,\n    worldPointer:pointer,\n    renderCurrent(){render(clock);},\n    eventTimes:()=>prefs.scene===\'city\'?{train:trainTime,cat:catTime}:activeWorld?.state().triggers,\n    disposeRenderer(){active=false;hostPaused=true;stop();activeWorld?.dispose();activeWorld=null;transition=null;for(const layer of [...Object.values(layers),reflection,composition]){layer.width=1;layer.height=1;}},', 'private lifecycle hooks');

const prelude = `'use strict';
(function(global){
  const instances=new WeakMap();
  const allowedKeys=new Set(['palette','weather','intensity','quality','windows','parallax','caption','reduced','worldActivity','worldGlow','worldFeature']);
  function create(output){
    if(!output||typeof output.getContext!=='function')throw new TypeError('Afterlight requires a canvas');
    if(!global.SeneschalAfterlightWorlds)throw new Error('Load afterlight-worlds.js before afterlight-engine.js');
    instances.get(output)?.dispose();
    const realDocument=global.document, cleanups=[], pending=new Set(), memory=new Map();
    let disposed=false,createdLayers=0;
    output.width=960;output.height=540;
    function listen(target,type,listener,options){
      if(disposed||!target?.addEventListener)return;
      target.addEventListener(type,listener,options);
      cleanups.push(()=>target.removeEventListener(type,listener,options));
    }
    // All source globals are lexically scoped. No Afterlight host API, desktop
    // bridge, preference record, input handler or application event escapes.
    const window={AfterlightWorlds:global.SeneschalAfterlightWorlds,addEventListener:(...args)=>listen(global,...args)};
    const document={
      getElementById:id=>id==='scene'?output:null,
      createElement(name){if(name!=='canvas')throw new Error('Only canvas layers are supported');createdLayers++;return realDocument.createElement('canvas');},
      get hidden(){return Boolean(realDocument.hidden);},
      body:{classList:{toggle(){},remove(){}}},
      addEventListener:(...args)=>listen(realDocument,...args)
    };
    const performance=global.performance;
    const localStorage={getItem:key=>memory.get(key)||null,setItem:(key,value)=>memory.set(key,String(value))};
    const dispatchEvent=()=>true;
    const matchMedia=query=>{
      const q=global.matchMedia?global.matchMedia(query):{matches:false};
      return{get matches(){return Boolean(q.matches);},addEventListener:(...args)=>listen(q,...args)};
    };
    const requestAnimationFrame=callback=>{
      if(disposed)return 0;
      let id=global.requestAnimationFrame(now=>{pending.delete(id);if(!disposed)callback(now);});pending.add(id);return id;
    };
    const cancelAnimationFrame=id=>{pending.delete(id);global.cancelAnimationFrame(id);};
    const innerWidth=960,innerHeight=540;
`;
const postlude = `
    const source=window.Afterlight;
    // Seneschal owns persistence, rotation and audio permission. This renderer
    // is intentionally silent and exposes neither audio-capture nor host APIs.
    source.set({caption:false,volume:0,musicStrength:0,musicSpectrum:false,rotate:false,daycycle:false});
    function alive(fn){return(...args)=>disposed?undefined:fn(...args);}
    const api={
      select:alive(id=>source.selectScene(String(id).replace(/^afterlight-/,''))),
      set:alive(changes=>{const clean={};for(const [key,value]of Object.entries(changes||{}))if(allowedKeys.has(key))clean[key]=value;return source.set(clean);}),
      pause:alive(value=>source.pause(Boolean(value))),
      hostPause:alive(value=>source.hostPause(Boolean(value))),
      renderAt:alive(seconds=>{source.pause(true);const time=Number(seconds);source.previewAt(Number.isFinite(time)?time:0);}),
      renderCurrent:alive(()=>source.renderCurrent()),
      effect:alive((key,point)=>source.effect(key,Number.isFinite(point?.x)&&Number.isFinite(point?.y)?{x:point.x,y:point.y}:undefined)),
      pointer:alive((x,y,click=false)=>source.worldPointer(Number.isFinite(Number(x))?Number(x):480,Number.isFinite(Number(y))?Number(y):270,Boolean(click))),
      prefs:alive(()=>source.prefs()),
      defaults:alive(()=>source.defaults()),
      worlds:alive(()=>source.worlds()),
      hotspots:alive(()=>source.hotspots()),
      showHotspots:alive(value=>source.showHotspots(Boolean(value))),
      interactionState:alive(()=>source.interactionState()),
      diagnostics:()=>({...source.diagnostics(),eventTimes:{...source.eventTimes()},disposed,scheduledFrames:pending.size,trackedListeners:cleanups.length,createdLayers}),
      dispose(){
        if(disposed)return;
        source.disposeRenderer();disposed=true;
        for(const id of pending)global.cancelAnimationFrame(id);pending.clear();
        for(const cleanup of cleanups.splice(0))cleanup();
        memory.clear();
        if(instances.get(output)===api)instances.delete(output);
      }
    };
    instances.set(output,api);
    return api;
  }
  global.SeneschalAfterlight=Object.freeze({version:'1.7-seneschal-2',create});
})(window);
`;
const engineOutput=stamp+prelude+body+postlude;
if (/\beval\s*\(|new\s+Function\s*\(|<iframe/i.test(engineOutput))throw new Error('Unsafe dynamic execution in generated renderer');
fs.mkdirSync(destination,{recursive:true});
fs.writeFileSync(path.join(destination,'afterlight-worlds.js'),worldOutput);
fs.writeFileSync(path.join(destination,'afterlight-engine.js'),engineOutput);
console.log(JSON.stringify({sourceRoot,files:['afterlight-worlds.js','afterlight-engine.js'],sourceHashes:{worlds:sha(worldsRaw),scene:sha(sceneRaw)},bytes:Buffer.byteLength(worldOutput)+Buffer.byteLength(engineOutput)},null,2));
